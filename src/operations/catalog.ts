export function operationById(id: string): OperationDefinition {
  const definition = operationCatalog.find((candidate) => candidate.id === id);
  if (!definition) throw new Error(`Unknown operation ${id}.`);
  return definition;
}

export function cliRootNames(catalog: readonly OperationDefinition[] = operationCatalog): string[] {
  return [...new Set(catalog.flatMap((definition) => (definition.cli ? [definition.cli.path[0]!] : [])))];
}
