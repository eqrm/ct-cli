export type JsonSchema = Record<string, unknown>;
export type HttpMethod = "GET" | "POST" | "DELETE";

export interface OperationParameter {
  name: string;
  description: string;
  schema: JsonSchema;
  required?: boolean;
  sensitive?: boolean;
  cli?: { kind: "argument" | "option"; name: string };
  http?: { in: "path" | "query" | "header" | "body"; name?: string };
  /** Restrict this parameter to one action of a multi-stage operation. */
  actions?: readonly string[];
}

export interface OperationHttpProjection {
  method: HttpMethod;
  path: string;
  action?: string;
  successStatus?: number;
  responseMediaType?: "application/json" | "text/html";
}

export interface OperationDefinition {
  id: string;
  summary: string;
  /** Longer transport-neutral explanation shown by generated API documentation. */
  description?: string;
  mutation: boolean;
  longRunning: boolean;
  capabilities: readonly ("read" | "plan" | "mutate" | "credentials")[];
  parameters: readonly OperationParameter[];
  resultSchema: JsonSchema;
  cli?: { path: readonly string[] };
  http?: readonly OperationHttpProjection[];
  adapterSpecific?: "cli" | "http";
}

